"""rename_opportunities_to_jobs_and_fix_applications_unique

Revision ID: 0001
Revises: (initial — no parent)
Create Date: 2026-05-14

WHAT THIS MIGRATION DOES
─────────────────────────
ARCH-5  Rename the main table from `opportunities` to `jobs`.
        A backwards-compatible view `opportunities` is created so that
        the Streamlit dashboard, db_sync.py, and any other legacy code
        that still says FROM opportunities keeps working without a single
        line change.  The view is a thin SELECT * wrapper — reads and
        writes pass through it transparently on Postgres 9.3+.

ARCH-7  Remove the UNIQUE(job_id) constraint that prevents a user from
        re-applying to a job after rejection, or from tracking the same
        job via different channels.  Replace it with two partial unique
        indexes that enforce the right invariants per access mode:

        idx_applications_job_id_personal
          UNIQUE on job_id WHERE user_id IS NULL
          → one application per job in single-user / personal mode.

        idx_applications_user_job_multiuser
          UNIQUE on (user_id, job_id) WHERE user_id IS NOT NULL
          → one application per (user, job) pair in multi-user mode.

        Together they preserve deduplication without blocking either
        re-apply workflows (delete first, then re-insert) or future
        multi-tenancy.

        The applications.job_id FK now points to `jobs(id)`.
        Postgres automatically updates FK target names on table rename,
        so no manual FK drop/re-add is needed here.

TRIGGER UPDATE
        The sync_application_to_opportunity trigger function (added in
        migrate_v3.py) referred to the old table name `opportunities`.
        It is recreated here pointing at `jobs` so stage changes in
        the Tracker tab continue to mirror into the legacy columns
        (applied, response_status, interview_stage) on the jobs table.

ROLLBACK
        downgrade() reverses every change: drops the view, renames the
        table back, drops the partial indexes, and restores the original
        UNIQUE constraint.
"""
