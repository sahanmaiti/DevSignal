def _rename_index_if_exists(old_name: str, new_name: str) -> None:
    """
    Renames a Postgres index only if `old_name` exists.
    Safe to call on a freshly initialised DB that has never had these indexes.
    """
    op.execute(f"""
        DO $$
        BEGIN
            IF EXISTS (
                SELECT 1 FROM pg_indexes
                WHERE indexname = '{old_name}'
            ) THEN
                ALTER INDEX {old_name} RENAME TO {new_name};
            END IF;
        END $$;
    """)
